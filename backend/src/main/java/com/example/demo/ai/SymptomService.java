package com.example.demo.ai;

import com.example.demo.ai.dto.SymptomRequest;
import com.example.demo.ai.dto.SymptomResponse;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.springframework.stereotype.Service;
import reactor.core.publisher.Mono;

import java.util.ArrayList;
import java.util.List;
import java.util.Set;

/**
 * Turns a free-text symptom description into structured, non-diagnostic guidance
 * via a JSON-mode completion. Always returns a usable response — falling back to
 * safe, clearly-labelled demo content when AI is not configured.
 */
@Service
public class SymptomService {

    private static final String DISCLAIMER =
            "This is general information generated by AI, not a medical diagnosis. "
                    + "Always consult a qualified healthcare professional for personal medical advice, "
                    + "and seek emergency care for severe or sudden symptoms.";

    private static final Set<String> URGENCIES = Set.of("LOW", "MODERATE", "URGENT", "EMERGENCY");

    private static final String SYSTEM_PROMPT = """
            You are a careful clinical triage assistant. Given a person's described symptoms,
            return structured, educational guidance. You do NOT diagnose; you outline
            possibilities and sensible next steps.

            Respond with a SINGLE JSON object matching EXACTLY this shape (no extra keys):
            {
              "summary": "one or two sentence plain-language summary of what they described",
              "urgency": "LOW | MODERATE | URGENT | EMERGENCY",
              "urgencyReason": "short reason for the urgency level",
              "possibleConditions": [
                { "name": "condition name", "likelihood": "low | moderate | high",
                  "description": "one plain-language sentence" }
              ],
              "recommendedActions": ["concrete next step", "..."],
              "selfCare": ["safe self-care tip", "..."],
              "seekCareIf": ["warning sign that means seek urgent care", "..."]
            }

            Rules:
            - Use EMERGENCY for red flags (e.g. chest pain with sweating, trouble breathing,
              stroke signs, severe bleeding, suicidal thoughts) and tell them to call emergency
              services in recommendedActions.
            - Provide 2-4 possibleConditions, most likely first. Never state certainty.
            - Keep every string concise and layperson-friendly.
            - Output ONLY the JSON object, nothing else.
            """;

    private final OpenAiClient client;
    private final AiProperties props;
    private final ObjectMapper mapper;

    public SymptomService(OpenAiClient client, AiProperties props, ObjectMapper mapper) {
        this.client = client;
        this.props = props;
        this.mapper = mapper;
    }

    public Mono<SymptomResponse> analyze(SymptomRequest req) {
        String text = req.text() == null ? "" : req.text().trim();
        if (text.isEmpty()) {
            return Mono.error(new AiException("Please describe your symptoms first."));
        }
        if (!props.isConfigured()) {
            return Mono.just(demoResponse(text));
        }

        String userPrompt = buildUserPrompt(req, text);
        List<AiMessage> messages = List.of(
                AiMessage.system(SYSTEM_PROMPT),
                AiMessage.user(userPrompt));

        return client.complete(messages, 0.2, true)
                .map(this::parse);
    }

    private String buildUserPrompt(SymptomRequest req, String text) {
        StringBuilder sb = new StringBuilder("Symptoms: ").append(text);
        if (req.age() != null) sb.append("\nAge: ").append(req.age());
        if (req.sex() != null && !req.sex().isBlank()) sb.append("\nSex: ").append(req.sex());
        if (req.duration() != null && !req.duration().isBlank()) sb.append("\nDuration: ").append(req.duration());
        return sb.toString();
    }

    private SymptomResponse parse(String json) {
        try {
            JsonNode root = mapper.readTree(json);

            String urgency = root.path("urgency").asText("MODERATE").toUpperCase();
            if (!URGENCIES.contains(urgency)) urgency = "MODERATE";

            List<SymptomResponse.Condition> conditions = new ArrayList<>();
            for (JsonNode c : root.path("possibleConditions")) {
                conditions.add(new SymptomResponse.Condition(
                        c.path("name").asText(""),
                        c.path("likelihood").asText("moderate").toLowerCase(),
                        c.path("description").asText("")));
            }

            return new SymptomResponse(
                    root.path("summary").asText(""),
                    urgency,
                    root.path("urgencyReason").asText(""),
                    conditions,
                    stringList(root.path("recommendedActions")),
                    stringList(root.path("selfCare")),
                    stringList(root.path("seekCareIf")),
                    DISCLAIMER,
                    true);
        } catch (Exception e) {
            throw new AiException("Could not interpret the AI response. Please try again.", e);
        }
    }

    private List<String> stringList(JsonNode node) {
        List<String> out = new ArrayList<>();
        if (node.isArray()) {
            for (JsonNode n : node) {
                String s = n.asText("");
                if (!s.isBlank()) out.add(s);
            }
        }
        return out;
    }

    private SymptomResponse demoResponse(String text) {
        return new SymptomResponse(
                "You described: \"" + text + "\". AuraHealth is in demo mode, so this is general "
                        + "guidance rather than an AI analysis of your specific symptoms.",
                "MODERATE",
                "Without AI analysis we can't assess severity — use your judgement and watch for red flags.",
                List.of(
                        new SymptomResponse.Condition("Enable AI for a real analysis", "moderate",
                                "Set the OPENAI_API_KEY on the server to unlock personalized symptom triage.")),
                List.of(
                        "Note when the symptoms started and whether they're getting better or worse.",
                        "Rest, stay hydrated, and monitor how you feel over the next 24 hours.",
                        "Contact a healthcare professional if you're worried or symptoms persist."),
                List.of(
                        "Get plenty of rest and fluids.",
                        "Avoid strenuous activity until you feel better."),
                List.of(
                        "Chest pain, difficulty breathing, or fainting.",
                        "Severe or rapidly worsening symptoms.",
                        "Confusion, weakness on one side, or trouble speaking."),
                DISCLAIMER,
                false);
    }
}
